#!/usr/bin/env bash
# Regenerate the resolved constraints export for KS's all+test dependency surface.
#
# This intentionally avoids adding pip-tools as a project dependency: it resolves
# through a temporary virtualenv, installs KS with all optional parser extras plus
# test dependencies, and exports the resolved environment with pip freeze.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

OUT="${1:-constraints.txt}"
PY_BIN="${PY:-python3}"
BASE_CONSTRAINTS="${BASE_CONSTRAINTS:-}"
UPDATE_PACKAGES="${UPDATE_PACKAGES:-}"
LINUX_REFERENCE_PACKAGES=(SecretStorage jeepney)
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

"$PY_BIN" -m venv "$WORK/venv"
"$WORK/venv/bin/python" -m pip install --quiet --disable-pip-version-check --upgrade pip
if [[ -n "$BASE_CONSTRAINTS" ]]; then
  if [[ ! -f "$BASE_CONSTRAINTS" ]]; then
    echo "baseline constraints not found: $BASE_CONSTRAINTS" >&2
    exit 2
  fi
  "$WORK/venv/bin/python" -m pip install --quiet --disable-pip-version-check \
    --constraint "$BASE_CONSTRAINTS" -e ".[all,test]"
else
  "$WORK/venv/bin/python" -m pip install --quiet --disable-pip-version-check -e ".[all,test]"
fi
# keyring selects these dependencies only on Linux. Resolve them explicitly so
# lock generation on another host still captures the documented Ubuntu graph.
linux_package_args=("${LINUX_REFERENCE_PACKAGES[@]}")
if [[ -n "$BASE_CONSTRAINTS" ]]; then
  "$WORK/venv/bin/python" -m pip install --quiet --disable-pip-version-check \
    --constraint "$BASE_CONSTRAINTS" "${linux_package_args[@]}"
else
  "$WORK/venv/bin/python" -m pip install --quiet --disable-pip-version-check \
    "${linux_package_args[@]}"
fi
if [[ -n "$UPDATE_PACKAGES" ]]; then
  read -r -a update_specs <<< "$UPDATE_PACKAGES"
  "$WORK/venv/bin/python" -m pip install --quiet --disable-pip-version-check \
    --upgrade "${update_specs[@]}"
fi
"$WORK/venv/bin/python" -m pip check >/dev/null

{
  echo "# Resolved constraints for EdgeForge Knowledge Server."
  echo "# Generated by scripts/generate-constraints.sh on ${SNAPSHOT_DATE:-$(date +%F)}."
  echo "# Regenerate with: make lock"
  echo "# Surface: project core + optional parser + test + Ubuntu conditional dependencies."
  echo "# Reference environment: CPython 3.11 on Ubuntu 24.04 x86_64."
  "$WORK/venv/bin/python" -m pip freeze --exclude-editable | sort -f
} > "${OUT}.tmp"
mv "${OUT}.tmp" "$OUT"
echo "constraints written to $OUT"
